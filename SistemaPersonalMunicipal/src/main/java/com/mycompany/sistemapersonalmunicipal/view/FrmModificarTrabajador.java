    private void btnDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarActionPerformed
        // TODO add your handling code here:
            String documento = txtDocumento.getText().trim();

        if (documento.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Primero debe buscar un trabajador."
            );

            return;
        }

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de desactivar al trabajador?",
                "Confirmar desactivación",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {

            TrabajadorDAO trabajadorDAO =
                    new TrabajadorDAO();

            boolean desactivado =
                    trabajadorDAO.desactivar(documento);

            if (desactivado) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Trabajador desactivado correctamente."
                );

                txtDocumento.setText("");
                txtNombre.setText("");
                txtCelular.setText("");
                txtCorreo.setText("");
                txtCodigoArea.setText("");
                txtCodigoCargo.setText("");

            } else {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No se pudo desactivar el trabajador."
                );
            }
        }
    }//GEN-LAST:event_btnDesactivarActionPerformed

    private void btnReactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReactivarActionPerformed
        // TODO add your handling code here:
        String documento = txtDocumento.getText().trim();

        if (documento.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el documento del trabajador que desea reactivar."
            );

            return;
        }

        TrabajadorDAO trabajadorDAO =
                new TrabajadorDAO();

        Object[] trabajador =
                trabajadorDAO.buscarIncluyendoInactivos(documento);

        if (trabajador == null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No existe un trabajador con ese documento."
            );

            return;
        }

        boolean estadoActual =
                (boolean) trabajador[2];

        if (estadoActual) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El trabajador ya se encuentra activo."
            );

            return;
        }

        int respuesta =
                javax.swing.JOptionPane.showConfirmDialog(
                        this,
                        "Trabajador: " + trabajador[1] + "\n"
                        + "¿Desea reactivarlo?",
                        "Confirmar reactivación",
                        javax.swing.JOptionPane.YES_NO_OPTION
                );

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {

            boolean reactivado =
                    trabajadorDAO.reactivar(documento);

            if (reactivado) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Trabajador reactivado correctamente."
                );

                txtDocumento.setText("");
                txtNombre.setText("");
                txtCelular.setText("");
                txtCorreo.setText("");
                txtCodigoArea.setText("");
                txtCodigoCargo.setText("");

            } else {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No se pudo reactivar el trabajador."
                );
            }
        }
    }//GEN-LAST:event_btnReactivarActionPerformed

