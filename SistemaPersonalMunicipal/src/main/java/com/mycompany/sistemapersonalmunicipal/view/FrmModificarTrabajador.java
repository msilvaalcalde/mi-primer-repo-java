    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String documento = txtDocumento.getText().trim();
        String celular = txtCelular.getText().trim();
        String correo = txtCorreo.getText().trim();
        String regimen = cboRegimen.getSelectedItem().toString();

        String codigoArea = txtCodigoArea.getText().trim();
        String codigoCargo = txtCodigoCargo.getText().trim();


        // ================= VALIDACIONES =================

        if (documento.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Primero debe buscar un trabajador."
            );

            return;
        }


        if (!celular.matches("\\d{9}")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El celular debe contener exactamente 9 dígitos numéricos."
            );

            return;
        }


        if (!correo.matches("^[\\w.-]+@[\\w.-]+\\.[A-Za-z]{2,}$")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un correo electrónico válido."
            );

            return;
        }


        if (codigoArea.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el código del área."
            );

            return;
        }


        if (codigoCargo.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el código del cargo."
            );

            return;
        }


        // ================= ACTUALIZAR =================

        TrabajadorDAO trabajadorDAO = new TrabajadorDAO();

        boolean actualizado = trabajadorDAO.actualizar(
                documento,
                celular,
                correo,
                regimen,
                codigoArea,
                codigoCargo
        );


        if (actualizado) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Trabajador actualizado correctamente."
            );

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se pudo actualizar el trabajador.\n"
                    + "Verifique los códigos de área y cargo.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }   
    }//GEN-LAST:event_btnActualizarActionPerformed

