    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String documento = txtDocumento.getText().trim();

        if (documento.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un número de documento."
            );

            return;
        }

        TrabajadorDAO trabajadorDAO = new TrabajadorDAO();

        Object[] datos =
                trabajadorDAO.buscarDatosParaModificar(documento);

        if (datos == null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se encontró un trabajador activo con ese documento."
            );

            txtNombre.setText("");
            txtCelular.setText("");
            txtCorreo.setText("");
            txtCodigoArea.setText("");
            txtCodigoCargo.setText("");

        } else {

            txtNombre.setText(datos[0].toString());
            txtCelular.setText(datos[1].toString());
            txtCorreo.setText(datos[2].toString());

            cboRegimen.setSelectedItem(
                    datos[3].toString()
            );

            txtCodigoArea.setText(
                    datos[4].toString()
            );

            txtCodigoCargo.setText(
                    datos[5].toString()
            );
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

