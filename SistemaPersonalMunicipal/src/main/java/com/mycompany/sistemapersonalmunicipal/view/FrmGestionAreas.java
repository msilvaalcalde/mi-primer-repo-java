    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigoArea.getText().trim();
        String nombre = txtNombreArea.getText().trim();

        if (codigo.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el código del área."
            );

            return;
        }

        if (nombre.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el nombre del área."
            );

            return;
        }

        AreaDAO areaDAO = new AreaDAO();

        boolean registrado = areaDAO.insertar(
                codigo,
                nombre
        );

        if (registrado) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Área registrada correctamente."
            );

            txtCodigoArea.setText("");
            txtNombreArea.setText("");

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se pudo registrar el área.\n"
                    + "Verifique que el código no esté duplicado.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
   
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
            String codigo = txtCodigoArea.getText().trim();

        if (codigo.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el código del área."
            );

            return;
        }

        AreaDAO areaDAO = new AreaDAO();

        Object[] area =
                areaDAO.buscarPorCodigo(codigo);

        if (area == null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se encontró un área activa con ese código."
            );

            txtNombreArea.setText("");

        } else {

            txtCodigoArea.setText(
                    area[1].toString()
            );

            txtNombreArea.setText(
                    area[2].toString()
            );

            txtAreaListado.setText(
                    "ÁREA ENCONTRADA\n"
                    + "====================================\n\n"
                    + "ID: " + area[0] + "\n"
                    + "Código: " + area[1] + "\n"
                    + "Nombre: " + area[2]
            );
        }
    
    }//GEN-LAST:event_btnBuscarActionPerformed

