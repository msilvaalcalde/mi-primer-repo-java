    private void btnReactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReactivarActionPerformed
        // TODO add your handling code here:
    String codigo = txtCodigoArea.getText().trim();

        if (codigo.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el código del área que desea reactivar."
            );

            return;
        }

        AreaDAO areaDAO = new AreaDAO();

        Object[] area =
                areaDAO.buscarPorCodigoIncluyendoInactivos(codigo);

        if (area == null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No existe un área con ese código."
            );

            return;
        }

        boolean estadoActual =
                (boolean) area[3];

        if (estadoActual) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El área ya se encuentra activa."
            );

            return;
        }

        boolean reactivada =
                areaDAO.reactivar(codigo);

        if (reactivada) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Área reactivada correctamente."
            );

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se pudo reactivar el área."
            );
        }
    }//GEN-LAST:event_btnReactivarActionPerformed

