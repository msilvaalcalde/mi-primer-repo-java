    private void btnDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarActionPerformed
        // TODO add your handling code here:
            String codigo = txtCodigoArea.getText().trim();

        if (codigo.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Primero busque o ingrese el código del área."
            );

            return;
        }

        int respuesta =
                javax.swing.JOptionPane.showConfirmDialog(
                        this,
                        "¿Está seguro de desactivar esta área?",
                        "Confirmar desactivación",
                        javax.swing.JOptionPane.YES_NO_OPTION
                );

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {

            AreaDAO areaDAO = new AreaDAO();

            boolean desactivada =
                    areaDAO.desactivar(codigo);

            if (desactivada) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Área desactivada correctamente."
                );

                txtCodigoArea.setText("");
                txtNombreArea.setText("");
                txtAreaListado.setText("");

            } else {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No se pudo desactivar el área."
                );
            }
        }
       
    }//GEN-LAST:event_btnDesactivarActionPerformed

    private void btnListarTodosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarTodosActionPerformed
                // TODO add your handling code here:
        AreaDAO areaDAO = new AreaDAO();

        java.util.List<Object[]> lista =
                areaDAO.listarTodas();

        if (lista.isEmpty()) {

            txtAreaListado.setText(
                    "No hay áreas activas registradas."
            );

            return;
        }

        StringBuilder texto = new StringBuilder();

        texto.append("LISTADO DE ÁREAS\n");
        texto.append("====================================\n\n");

        for (Object[] fila : lista) {

            texto.append("ID: ")
                    .append(fila[0])
                    .append("\n");

            texto.append("Código: ")
                    .append(fila[1])
                    .append("\n");

            texto.append("Nombre: ")
                    .append(fila[2])
                    .append("\n");

            texto.append("------------------------------------\n\n");
        }

        txtAreaListado.setText(texto.toString());
    }//GEN-LAST:event_btnListarTodosActionPerformed

